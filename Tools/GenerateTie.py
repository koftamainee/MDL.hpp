#!/usr/bin/env python3
"""Generates Source/Public/MDL/Detail/Tie.h: structured-binding based field access for aggregates."""
import pathlib
import sys

MAX_FIELDS = int(sys.argv[1]) if len(sys.argv) > 1 else 64

out = [
    "#pragma once",
    "",
    f"// Generated by Tools/GenerateTie.py ({MAX_FIELDS} fields). Do not edit.",
    "",
    "#include <MDL/Types.h>",
    "",
    "#include <tuple>",
    "",
    "",
    "namespace MDL::Detail {",
    "",
    f"inline constexpr usize MaxReflectedFields = {MAX_FIELDS};",
    "",
    "template <usize N, class T>",
    "constexpr auto Tie(T &obj) {",
    "    if constexpr (N == 0) {",
    "        return std::tuple<> {};",
]
for n in range(1, MAX_FIELDS + 1):
    names = ", ".join(f"f{i}" for i in range(n))
    out += [
        f"    }} else if constexpr (N == {n}) {{",
        f"        auto &[{names}] = obj;",
        f"        return std::tie({names});",
    ]
out += [
    "    } else {",
    f'        static_assert(N <= MaxReflectedFields, "MDL: too many fields, regenerate Tie.h with a bigger limit");',
    "    }",
    "}",
    "",
    "} // namespace MDL::Detail",
    "",
]
path = pathlib.Path(__file__).resolve().parent.parent / "Source/Public/MDL/Detail/Tie.h"
path.write_text("\n".join(out))
print(f"wrote {path}")
